//! Generates `docs/ERRORS.md` from the error-surface branch registry.
//!
//! Run from the workspace root:
//!
//! ```bash
//! cargo run -p streampay-contract --example error_surface_doc
//! ```
//!
//! CI runs this and then `git diff --exit-code docs/ERRORS.md`, so the table can
//! never drift from `surface.rs` / `errors.rs`. Because the document is emitted
//! from the same table the tests are generated from, there is no hand-maintained
//! mapping to keep in sync.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::PathBuf;

use streampay_contract::surface::{Branch, Reachability, RETIRED_CODES};
use streampay_contract::StreamError;

fn entrypoints_for(code: StreamError) -> Vec<&'static str> {
    let mut set = BTreeSet::new();
    for branch in Branch::ALL.iter().filter(|b| b.error() == code) {
        for ep in branch.entrypoints() {
            set.insert(*ep);
        }
    }
    set.into_iter().collect()
}

fn branches_for(code: StreamError) -> Vec<Branch> {
    Branch::ALL
        .iter()
        .copied()
        .filter(|b| b.error() == code)
        .collect()
}

fn main() {
    let mut out = String::new();

    out.push_str(
        "<!-- Generated by `cargo run -p streampay-contract --example error_surface_doc`. \
         Do not edit by hand — edit `src/surface.rs` / `src/errors.rs` and regenerate. -->\n\n",
    );
    out.push_str("# StreamPay error surface\n\n");
    out.push_str(
        "Every expected failure is a `StreamError` with a stable numeric code. This \
         document is generated from the contract's instrumentation (`src/surface.rs`): each \
         row is a *branch* — one `(entrypoint, condition)` validation decision — mapped to \
         the code it returns. The `error_surface_test.rs` matrix proves every reachable \
         branch fires its code and every code is produced (or retired).\n\n",
    );

    // --- Error code table ---------------------------------------------------
    out.push_str("## Error codes\n\n");
    out.push_str("| Code | Variant | Status | Processed by | Meaning |\n");
    out.push_str("| ---: | --- | --- | --- | --- |\n");

    for &code in StreamError::ALL.iter() {
        let branches = branches_for(code);
        let retired = RETIRED_CODES.contains(&code);
        let status = if retired {
            "**retired** (unreachable)".to_string()
        } else {
            format!("reachable ({} branch(es))", branches.len())
        };
        let produced = if retired {
            "—".to_string()
        } else {
            let eps = entrypoints_for(code);
            eps.iter()
                .map(|e| format!("`{e}`"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        let variant = format!("`{:?}`", code);
        let meaning: String = if retired {
            retired_meaning(code).unwrap_or("—").to_string()
        } else {
            reachable_meaning(code)
        };
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            code.code(),
            variant,
            status,
            produced,
            meaning
        );
    }

    // --- Branch matrix ------------------------------------------------------
    out.push_str("\n## Branch matrix (entrypoint × condition → error)\n\n");
    out.push_str("| Branch | Entrypoint(s) | Error | Code | Condition | Reachability |\n");
    out.push_str("| --- | --- | --- | ---: | --- | --- |\n");

    for branch in Branch::ALL.iter() {
        let eps = branch
            .entrypoints()
            .iter()
            .map(|e| format!("`{e}`"))
            .collect::<Vec<_>>()
            .join(", ");
        let reach = match branch.reachability() {
            Reachability::Reachable => "reachable",
            Reachability::Defensive => "defensive (unreachable)",
        };
        let _ = writeln!(
            out,
            "| `{:?}` | {} | `{:?}` | {} | {} | {} |",
            branch,
            eps,
            branch.error(),
            branch.error().code(),
            branch.condition(),
            reach
        );
    }

    // --- Retired codes ------------------------------------------------------
    out.push_str("\n## Retired codes\n\n");
    out.push_str(
        "Codes are append-only: a retired code is never renumbered, reused, or removed — \
         its numeric slot is reserved forever so existing clients keep decoding every code \
         they know. The coverage test (`every_error_code_is_produced_or_retired`) exempts \
         exactly the codes below; any *other* code with zero reachable branches fails CI.\n\n",
    );
    out.push_str("| Code | Variant | Why unreachable |\n| ---: | --- | --- |\n");
    for &code in RETIRED_CODES.iter() {
        let _ = writeln!(
            out,
            "| {} | `{:?}` | {} |",
            code.code(),
            code,
            retired_meaning(code).unwrap_or("—")
        );
    }

    // --- Instrumentation note ----------------------------------------------
    out.push_str("\n## Defensive branches\n\n");
    out.push_str(
        "A defensive branch is a `checked_*` guard whose precondition the contract's \
         invariants rule out for any stored stream. It has a code (so it is not a dead \
         *code*) but cannot be triggered; the matrix test asserts it never fires: ",
    );
    let defensive: Vec<Branch> = Branch::ALL
        .iter()
        .copied()
        .filter(|b| b.reachability() == Reachability::Defensive)
        .collect();
    if defensive.is_empty() {
        out.push_str("none.\n");
    } else {
        out.push_str(
            &defensive
                .iter()
                .map(|b| format!("`{b:?}`"))
                .collect::<Vec<_>>()
                .join(", "),
        );
        out.push_str(".\n");
    }

    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/ERRORS.md");
    std::fs::write(&path, out).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
    println!("wrote {}", path.display());
}

fn retired_meaning(code: StreamError) -> Option<&'static str> {
    match code {
        StreamError::NotStreamSender => Some(
            "Reserved role check from the original draft. The contract authorizes sender-only \
             actions by comparing the caller address directly and uses `NotAuthorized` (#12) \
             otherwise, so this variant is never returned. Retained for wire compatibility.",
        ),
        StreamError::NotStreamRecipient => Some(
            "Reserved role check from the original draft. Recipient-only actions require the \
             recipient's authorization (`require_auth`) and use `NotAuthorized` (#12) for \
             business-rule rejections, so this variant is never returned. Retained for wire \
             compatibility.",
        ),
        _ => None,
    }
}

fn reachable_meaning(code: StreamError) -> String {
    // The first branch's condition is representative for codes with one branch;
    // for shared codes, list each producing condition.
    let branches = branches_for(code);
    branches
        .iter()
        .map(|b| b.condition())
        .collect::<Vec<_>>()
        .join("; ")
}
