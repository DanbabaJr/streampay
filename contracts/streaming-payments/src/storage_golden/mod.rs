/// Stable, address-independent kind name for a storage key: the snake-case
/// of the `DataKey`/`PolicyDataKey` variant (or `contract_instance`). This
/// is the manifest's dispatch key: adding a new storage variant without a
/// dispatch arm here fails the generator and the decode test by
/// construction, which is the point.
pub(crate) fn kind_for_key(env: &Env, key_sc: &xdr::ScVal) -> Option<String> {
    use crate::policy::PolicyDataKey;
    use crate::stream::DataKey;
    if key_sc == &xdr::ScVal::LedgerKeyContractInstance {
        return Some("contract_instance".to_string());
    }
    if let Ok(dk) = DataKey::try_from_val(env, key_sc) {
        return Some(sanitize(match dk {
            DataKey::NextStreamId => "next_stream_id",
            DataKey::Stream(_) => "stream",
            DataKey::RecipientStreams(_) => "recipient_streams",
            DataKey::SenderStreams(_) => "sender_streams",
            DataKey::NextIntentId => "next_intent_id",
            DataKey::Intent(_) => "intent",
            DataKey::SenderIntents(_) => "sender_intents",
            DataKey::Governor => "governor",
            DataKey::PendingGovernor => "pending_governor",
            DataKey::FeeBps => "fee_bps",
            DataKey::Treasury(_) => "treasury",
            DataKey::StreamFee(_) => "stream_fee",
            DataKey::SchemaVersion => "schema_version",
            DataKey::ContractFrozen => "contract_frozen",
            DataKey::PendingUpgrade => "pending_upgrade",
            DataKey::MigrationCursor => "migration_cursor",
            // Dispatched so the generator labels them, but the committed corpus
            // has no record of these nine kinds yet — they entered `DataKey`
            // after the corpus was cut. `COVERED_KINDS` in `decode.rs` stays the
            // list of kinds CI actually pins.
            DataKey::OracleConfig => "oracle_config",
            DataKey::OracleReport(_) => "oracle_report",
            DataKey::PendingOwnership(_) => "pending_ownership",
            DataKey::PendingRateChange(_) => "pending_rate_change",
            DataKey::RateSegments(_) => "rate_segments",
            DataKey::PendingSenderTransfer(_) => "pending_sender_transfer",
            DataKey::SenderHistory(_) => "sender_history",
            DataKey::RefundTarget(_) => "refund_target",
            DataKey::StreamPause(_) => "stream_pause",
        }));
    }
    if let Ok(pk) = PolicyDataKey::try_from_val(env, key_sc) {
        return Some(sanitize(match pk {
            PolicyDataKey::Admin => "admin",
            PolicyDataKey::PendingAdmin => "pending_admin",
            PolicyDataKey::TimelockDelay => "timelock_delay",
            PolicyDataKey::Asset(_) => "asset",
            PolicyDataKey::QueuedAsset(_) => "queued_asset",
            PolicyDataKey::StreamPolicy(_) => "stream_policy",
            PolicyDataKey::GlobalStreamPolicy => "global_stream_policy",
        }));
    }
    None
}

/// Filesystem-safe record name derived from a label.
pub(crate) fn sanitize(label: &str) -> String {
    let mut out = String::new();
    for c in label.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('_') {
            out.push('_');
        }
    }
    let trimmed = out.trim_matches('_').to_string();
    // Address-keyed labels differ only past char 40 of the strkey; cap length
    // and rely on the manifest `key` render for exact identity.
    if trimmed.len() > 48 {
        trimmed[..48].to_string()
    } else {
        trimmed
    }
}

// ------------------------------------------------------- field-level diffs --

/// Flattens a golden value ScVal into (field name -> render) pairs for the
/// manifest and the decode diff. Struct maps key by field symbol; everything
/// else lives under the single `value` key. Instance entries flatten their
/// per-key storage entries.
pub(crate) fn fields_of(env: &Env, kind: &str, val: &xdr::ScVal) -> BTreeMap<String, String> {
    let mut out = BTreeMap::new();
    match (kind, val) {
        ("contract_instance", xdr::ScVal::ContractInstance(inst)) => {
            let exec = match &inst.executable {
                xdr::ContractExecutable::Wasm(h) => format!("wasm:{}", hex(&h.0)),
                other => format!("{other:?}"),
            };
            out.insert("executable".to_string(), exec);
            if let Some(m) = &inst.storage {
                for e in m.0.iter() {
                    out.insert(
                        format!("storage[{}]", render(env, &e.key)),
                        render(env, &e.val),
                    );
                }
            }
            out
        }
        (_, xdr::ScVal::Map(Some(m))) => {
            for e in m.0.iter() {
                let key = match &e.key {
                    xdr::ScVal::Symbol(s) => s.to_utf8_string_lossy(),
                    other => render(env, other),
                };
                out.insert(key, render(env, &e.val));
            }
            out
        }
        _ => {
            out.insert("value".to_string(), render(env, val));
            out
        }
    }
}

// ------------------------------------------------------------- manifest ----

/// One committed storage record and its field-level golden rendering.
///
/// `kind` is a stable, environment-independent name derived from the
/// storage-key variant (never from an address); `key` is the full `render`
/// of the ScVal key for human review; `fields` maps each field name to its
/// golden rendering. The decode test diffs these field-by-field after
/// decoding the blob with the in-development types.
#[derive(Serialize, Deserialize)]
pub(crate) struct RecordMeta {
    pub file: String,
    pub kind: String,
    pub durability: String,
    pub key: String,
    pub fields: BTreeMap<String, String>,
}

/// One committed event payload, keyed by event name (first topic).
#[derive(Serialize, Deserialize)]
pub(crate) struct EventMeta {
    pub file: String,
    pub name: String,
    pub topics: String,
    pub data: String,
    pub fields: BTreeMap<String, String>,
}

#[derive(Serialize, Deserialize)]
pub(crate) struct Manifest {
    pub records: Vec<RecordMeta>,
    pub events: Vec<EventMeta>,
}

pub(crate) fn read_manifest() -> Manifest {
    let text = std::fs::read_to_string(manifest_path())
        .expect("test_fixtures/storage/manifest.json missing; run the generator (see docs/STORAGE_LAYOUT.md)");
    serde_json::from_str(&text).expect("manifest.json is not valid JSON")
}

/// Field-for-field diff of two flattened record maps. The returned strings
/// name the exact field that changed (missing / unexpected / mismatched
/// value), which is what the failure message must show — not "bytes differ".
pub(crate) fn diff_fields(
    label: &str,
    want: &BTreeMap<String, String>,
    got: &BTreeMap<String, String>,
) -> Vec<String> {
    let mut diffs = Vec::new();
    for (k, w) in want {
        match got.get(k) {
            None => diffs.push(format!(
                "{label}.{k}: present in golden, MISSING after decode"
            )),
            Some(g) if g != w => diffs.push(format!("{label}.{k}: golden={w} decoded={g}")),
            Some(_) => {}
        }
    }
    for (k, g) in got {
        if !want.contains_key(k) {
            diffs.push(format!(
                "{label}.{k}: NOT IN GOLDEN, appeared after decode (g={g})"
            ));
        }
    }
    diffs
}

// ------------------------------------------------- compatible additions ----

/// A field the current build *adds* on re-encode whose value renders as
/// `void` is the wire signature of an `Option` field introduced after the
/// corpus was cut, which is a compatible addition rather than a layout
/// regression — so `decode` reports it as a note instead of a failure.
///
/// The signature is exact, not a guess. The generated decoder unpacks a
/// struct with `sparse_map_unpack_to_slice(&KEYS, &mut vals)` over a
/// `VALS = [VOID; N]` initialiser, so a key the release line never wrote
/// stays VOID on the way in, and the encoder writes every declared field
/// back out, so that VOID reaches the wire as an explicit entry. VOID is
/// only ever accepted by `Option<T>`: a *required* field added since the cut
/// makes the typed decode itself fail (`VOID -> bool` / `-> u64` / … is a
/// `ConversionError`) long before this filter runs, so nothing that would
/// actually break an on-ledger read can hide behind it. Renames, removals and
/// retyped fields keep failing through the strict arms of `diff_fields`.
pub(crate) fn optional_additions(
    golden: &BTreeMap<String, String>,
    got: &BTreeMap<String, String>,
) -> Vec<String> {
    got.iter()
        .filter(|(k, v)| v.as_str() == "void" && !golden.contains_key(*k))
        .map(|(k, _)| k.clone())
        .collect()
}

/// Drop rendered keys from a re-encoded map value so the byte-for-byte
/// comparison in `decode` runs against the release-line key set. Order among
/// the surviving entries is untouched, so the check still catches an ordering
/// or canonicalisation change; non-map values pass through unchanged.
pub(crate) fn without_added_keys(sc: &xdr::ScVal, keys: &[String]) -> xdr::ScVal {
    let xdr::ScVal::Map(Some(m)) = sc else {
        return sc.clone();
    };
    let kept: Vec<xdr::ScMapEntry> =
        m.0.iter()
            .filter(|e| match &e.key {
                xdr::ScVal::Symbol(s) => !keys.contains(&s.to_utf8_string_lossy()),
                _ => true,
            })
            .cloned()
            .collect();
    xdr::ScVal::Map(Some(xdr::ScMap(
        VecM::try_from(kept).expect("a subset of a valid map key set is valid"),
    )))
}
