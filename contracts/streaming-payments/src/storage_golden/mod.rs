//! Golden storage-layout regression suite (issue #210).
//!
//! Storage layout is silently broken by record changes that keep Rust
//! semantics but shift the on-ledger XDR — renamed fields and enum variants
//! (the symbol-named encoding writes variant/field names onto the wire),
//! retyped fields, and new or removed keys. This module builds the net:
//!
//! * `generate` — a `#[ignore]`d test that runs the release-line build,
//!   writes one instance of every persisted record type, and dumps the exact
//!   `LedgerKey`/`LedgerEntry` XDR (plus emitted-event XDR) and a
//!   field-level manifest under `test_fixtures/storage/`.
//! * `decode` — the CI test: decodes each committed fixture with the
//!   in-development types (`TryFromVal<Env, ScVal>` generated by
//!   `#[contracttype]`), asserts field-for-field round-trips, and diffs by
//!   field name (never "bytes differ" alone).
//! * `mid_enum` — proves by construction that mid-record semantic shifts
//!   (variant renames, discriminant/semantic drift) are caught by the pinned
//!   blobs, including a typed-decode-cannot-see-it demonstration.
//! * `replay` — upgrade replay: boots the baseline release wasm, writes
//!   data, upgrades the instance to the in-development build through the
//!   contract's own timelocked `execute_upgrade`, and reads the same keys
//!   back with a data-survival assertion set.
//!
//! Workflow for legitimately accepting a layout change: see
//! `docs/STORAGE_LAYOUT.md`.

