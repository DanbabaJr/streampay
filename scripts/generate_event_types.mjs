#!/usr/bin/env node
// TypeScript codegen for the event schema registry (issue #213).
//
// Reads the generated registry (`schemas/events/registry.json`) plus the
// per-event JSON Schemas and emits:
//   * indexer/src/generated/events.ts   — event types + runtime shape table
//   * frontend/lib/generated/events.ts  — same surface for the frontend
//   * docs/EVENTS.md                    — consumer-facing event catalogue
//
// CI runs this after the Rust generator and fails on `git diff` of the
// outputs, so a registry bump without regenerated types is caught, and the
// consumers can never drift from the contract's emitted shapes.
//
// Usage: node scripts/generate_event_types.mjs [--check]

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMAS = path.join(REPO_ROOT, "schemas", "events");

const OUTPUTS = [
  "indexer/src/generated/events.ts",
  "frontend/lib/generated/events.ts",
  "docs/EVENTS.md",
];

function readRegistry() {
  return JSON.parse(readFileSync(path.join(SCHEMAS, "registry.json"), "utf8"));
}

function readEventSchema(eventKey) {
  const p = path.join(SCHEMAS, `v1/events/${eventKey}.json`);
  if (!existsSync(p)) throw new Error(`missing event schema ${p} — run the Rust generator first`);
  return JSON.parse(readFileSync(p, "utf8"));
}

const TS_PRIMITIVES = {
  bool: "boolean",
  u32: "number",
  u64: "bigint",
  i64: "bigint",
  i128: "bigint",
  Address: "string",
  Symbol: "string",
  String: "string",
  "BytesN<32>": "Uint8Array",
};

function tsType(ty, definitions) {
  if (TS_PRIMITIVES[ty]) return TS_PRIMITIVES[ty];
  const option = ty.match(/^Option<(.+)>$/);
  if (option) return `${tsType(option[1], definitions)} | null`;
  const vec = ty.match(/^Vec<(.+)>$/);
  if (vec) return `${tsType(vec[1], definitions)}[]`;
  const bare = ty.split("::").pop();
  if (definitions[bare]) return bare;
  throw new Error(`registry type \`${ty}\` has no TypeScript mapping — extend TS_PRIMITIVES in scripts/generate_event_types.mjs`);
}

function header(kind, registryVersion) {
  const banner = (text) => `/* ${text.padEnd(74, " ")}*/`;
  return [
    banner("-".repeat(74)),
    banner("This file is auto-generated by `node scripts/generate_event_types.mjs`"),
    banner("from `schemas/events/registry.json`. Do not edit by hand — edit the"),
    banner("contract events (`contracts/streaming-payments/src/events.rs`), run the"),
    banner("registry generator, then regenerate this file. CI fails on drift."),
    banner(`Target: ${kind} (registry v${registryVersion}).`),
    banner("-".repeat(74)),
    "",
  ].join("\n");
}

function generateTs(registry) {
  const events = registry.events;
  const definitions = registry.definitions ?? {};
  const structNames = Object.keys(events).sort();
  const lines = [];
  lines.push(header("shared event contract between indexer and frontend", registry.registry_version));

  // Referenced contract types: structs by field, unit enums by variant symbol,
  // payload enums as a discriminated union of `[variant, payload…]`.
  for (const [name, def] of Object.entries(definitions)) {
    if (def.kind === "enum") {
      lines.push(`/** Contract enum \`${name}\`, wire-encoded as its variant symbol (fingerprint \`${def.fingerprint}\`). */`);
      lines.push(`export type ${name} = ${def.variants.map((v) => JSON.stringify(v)).join(" | ")};`, "");
      continue;
    }
    if (def.kind === "payload_enum") {
      lines.push(
        `/** Contract enum \`${name}\`, wire-encoded as \`[variant symbol, payload…]\` where the`,
        ` * variant discriminant selects the payload shape (fingerprint \`${def.fingerprint}\`). */`
      );
      lines.push(`export type ${name} =`);
      const members = def.variants.map((v) => {
        const payload =
          v.fields.length === 0
            ? "[]"
            : v.positional
              ? `[${v.fields.map((f) => tsType(f.type, definitions)).join(", ")}]`
              : `{ ${v.fields.map((f) => `${f.name}: ${tsType(f.type, definitions)}`).join("; ")} }`;
        return `  | { variant: ${JSON.stringify(v.name)}; payload: ${payload} }`;
      });
      lines.push(`${members.join("\n")};`, "");
      continue;
    }
    lines.push(`/** Contract struct \`${name}\` (referenced by event fields; fingerprint \`${def.fingerprint}\`). */`);
    lines.push(`export interface ${name} {`);
    for (const f of def.fields) {
      lines.push(`  ${f.name}: ${tsType(f.type, definitions)};`);
    }
    lines.push("}", "");
  }

  // One interface per event: topic fields first (positional on the wire),
  // then data fields — the shape a consumer sees after decoding.
  for (const structName of structNames) {
    const ev = events[structName];
    const schema = readEventSchema(ev.event_key);
    if (schema.description) lines.push(`/** ${schema.description} */`);
    lines.push(`/** Event key \`${ev.event_key}\` — fingerprint \`${ev.fingerprint}\`. */`);
    lines.push(`export interface ${structName}Event {`);
    for (const f of [...ev.topics, ...ev.data]) {
      lines.push(`  ${f.name}: ${tsType(f.type, definitions)};`);
    }
    lines.push("}", "");
  }

  // Event key table (the snake_case topic symbol Soroban publishes).
  lines.push("/** The topic symbol each event publishes as its name. */");
  lines.push("export const EVENT_KEYS = {");
  for (const structName of structNames) {
    lines.push(`  ${structName}: ${JSON.stringify(events[structName].event_key)},`);
  }
  lines.push("} as const;", "");

  lines.push("/** Union of every registered event's topic symbol. */");
  lines.push("export type ContractEventName = (typeof EVENT_KEYS)[keyof typeof EVENT_KEYS];");
  lines.push("");
  lines.push("/** Every event this registry knows about, even if a consumer ignores it. */");
  lines.push(
    `export const ALL_CONTRACT_EVENT_NAMES: readonly ContractEventName[] = [${structNames
      .map((s) => JSON.stringify(events[s].event_key))
      .join(", ")}] as const;`,
    ""
  );

  lines.push("/** Narrow an arbitrary RPC event name to a registered contract event. */");
  lines.push("export function isContractEventName(name: string): name is ContractEventName {");
  lines.push("  return (ALL_CONTRACT_EVENT_NAMES as readonly string[]).includes(name);");
  lines.push("}", "");

  lines.push("/** Decode helper: name the struct behind a registered event key. */");
  lines.push("export const EVENT_STRUCT_BY_KEY: Record<ContractEventName, string> = {");
  for (const structName of structNames) {
    lines.push(`  ${JSON.stringify(events[structName].event_key)}: ${JSON.stringify(structName)},`);
  }
  lines.push("}", "");

  lines.push("/** Per-event shape table (Rust type strings) for runtime validation. */");
  lines.push("export interface FieldShape {");
  lines.push("  /** Field name as it appears in the decoded event (snake_case). */");
  lines.push("  name: string;");
  lines.push("  /** Contract type, verbatim from the source (e.g. `u64`, `Address`, `Option<Address>`). */");
  lines.push("  type: string;");
  lines.push("}", "");
  lines.push("export interface EventShape {");
  lines.push("  struct: string;");
  lines.push("  eventKey: ContractEventName;");
  lines.push("  fingerprint: string;");
  lines.push("  /** Positional topic fields after the event-name symbol. */");
  lines.push("  topics: FieldShape[];");
  lines.push("  /** Symbol-keyed data fields. Additive-only: extra keys are allowed. */");
  lines.push("  data: FieldShape[];");
  lines.push("}", "");
  lines.push("export const EVENT_SHAPES: Record<ContractEventName, EventShape> = {");
  for (const structName of structNames) {
    const ev = events[structName];
    lines.push(
      `  ${JSON.stringify(ev.event_key)}: { struct: ${JSON.stringify(structName)}, eventKey: ${JSON.stringify(ev.event_key)}, fingerprint: ${JSON.stringify(ev.fingerprint)}, topics: ${JSON.stringify(ev.topics)}, data: ${JSON.stringify(ev.data)} },`
    );
  }
  lines.push("}", "");

  lines.push("/** Registry fingerprints keyed by event struct, for drift reporting. */");
  lines.push(`export const EVENT_FINGERPRINTS: Record<string, string> = ${JSON.stringify(registry.fingerprints, null, 2)};`);
  lines.push("");

  return lines.join("\n");
}

function generateDocs(registry) {
  const events = registry.events;
  const structNames = Object.keys(events).sort();
  const lines = [];
  lines.push("<!-- Generated by `node scripts/generate_event_types.mjs` from `schemas/events/registry.json`. Do not edit by hand. -->");
  lines.push("");
  lines.push("# StreamPay contract events");
  lines.push("");
  lines.push(
    "Every event the contract emits, with its on-chain topic layout and decoded data fields." +
      " This catalogue is generated: the registry (`schemas/events/`) is the machine-readable" +
      " source and CI enforces additive-only compatibility — see [schemas/events/README.md](../schemas/events/README.md)."
  );
  lines.push("");
  lines.push("| Event key | Struct | Topics (positional) | Data fields | Fingerprint |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const structName of structNames) {
    const ev = events[structName];
    const topics = ev.topics.map((t) => `\`${t.name}: ${t.type}\``).join(", ") || "—";
    const data = ev.data.map((t) => `\`${t.name}: ${t.type}\``).join(", ") || "—";
    lines.push(
      `| \`${ev.event_key}\` | \`${structName}\` | ${topics} | ${data} | \`${ev.fingerprint.slice(0, 18)}…\` |`
    );
  }
  const definitions = registry.definitions ?? {};
  if (Object.keys(definitions).length > 0) {
    lines.push("");
    lines.push("## Referenced contract types");
    for (const [name, def] of Object.entries(definitions)) {
      const shape =
        def.kind === "enum"
          ? `one of ${def.variants.map((v) => `\`${v}\``).join(", ")}`
          : def.kind === "payload_enum"
            ? `one of ${def.variants
                .map((v) =>
                  v.fields.length === 0
                    ? `\`${v.name}\``
                    : `\`${v.name}(${v.fields.map((f) => f.type).join(", ")})\``
                )
                .join(", ")}`
            : def.fields.map((f) => `\`${f.name}: ${f.type}\``).join(", ");
      lines.push(`- \`${name}\` (${def.kind ?? "struct"}): ${shape} (fingerprint \`${def.fingerprint.slice(0, 18)}…\`)`);
    }
  }
  lines.push("");
  lines.push("Decoding: the first topic is always the event key symbol; remaining topics are positional");
  lines.push("per the table above; the event value is a map keyed by the data field names.");
  lines.push("TypeScript types for all of this are generated into `indexer/src/generated/events.ts`");
  lines.push("and `frontend/lib/generated/events.ts`.");
  lines.push("");
  return lines.join("\n");
}

function main() {
  const check = process.argv.slice(2).includes("--check");
  const registry = readRegistry();
  const outputs = {
    "indexer/src/generated/events.ts": generateTs(registry),
    "frontend/lib/generated/events.ts": generateTs(registry),
    "docs/EVENTS.md": generateDocs(registry),
  };
  let drift = [];
  for (const [rel, text] of Object.entries(outputs)) {
    const p = path.join(REPO_ROOT, rel);
    const current = existsSync(p) ? readFileSync(p, "utf8") : null;
    if (current === text) continue;
    if (check) {
      drift.push(rel);
      continue;
    }
    mkdirSync(path.dirname(p), { recursive: true });
    writeFileSync(p, text);
    console.log(`wrote ${rel}`);
  }
  if (drift.length > 0) {
    console.error(`event type generation is stale:\n  ${drift.join("\n  ")}\nrun: node scripts/generate_event_types.mjs`);
    process.exit(1);
  }
  if (!check) console.log(`registry version ${registry.registry_version}, ${Object.keys(registry.events).length} events -> ${OUTPUTS.length} outputs`);
}

main();
