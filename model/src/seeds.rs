//! Corpus seeds derived from unit and property test scenarios.
//!
//! The fixed scenarios below are hand-written. Alongside them this module owns
//! the **seed-expansion contract**: the deterministic mapping from a `u64` seed
//! to a generated [`ActionSequence`]. The mapping is frozen by golden vectors in
//! `model/goldens/seed_expansion.txt` and documented in
//! `model/SEED_EXPANSION.md`; a platform-dependent expansion would make
//! differential failures unreproducible and CI flaky.
//!
//! Bumping [`SEED_EXPANSION_VERSION`] or changing [`SeedExpander`] requires
//! re-blessing those goldens (`npm run seed:golden:bless`).

use crate::action::{Action, ActionSequence};

const DAY: u32 = 86400;
const DEPOSIT: i128 = 10_000_000_000;

/// Version of the seed-expansion contract (algorithm, sampling and action
/// mapping). Any change that alters generated bytes must bump this and
/// re-bless the golden vectors.
pub const SEED_EXPANSION_VERSION: u32 = 1;

/// SplitMix64 increment: `floor(2^64 / golden ratio)`.
const SPLITMIX64_GAMMA: u64 = 0x9E37_79B9_7F4A_7C15;
const SPLITMIX64_MIX_1: u64 = 0xBF58_476D_1CE4_E5B9;
const SPLITMIX64_MIX_2: u64 = 0x94D0_49BB_1331_11EB;

/// Number of actions in a [`generate_sequence`] result.
pub const GENERATED_SEQUENCE_LEN: usize = 6;

/// Deterministic, platform-independent seed expander (SplitMix64).
///
/// All arithmetic is wrapping `u64` arithmetic, which Rust defines exactly on
/// every target, so the same seed yields the same word stream on Linux, macOS,
/// Windows and wasm32. The seed itself is consumed as a `u64` value, not as
/// bytes; when an external format needs bytes it uses little-endian
/// ([`SeedExpander::seed_bytes`]).
#[derive(Clone, Debug)]
pub struct SeedExpander {
    state: u64,
}

impl SeedExpander {
    /// Creates an expander for `seed`. Two expanders with the same seed yield
    /// the same sequence of [`next_u64`](Self::next_u64) values forever.
    pub fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    /// Returns the next 64-bit word of the stream.
    ///
    /// The first call for `seed = 0` is `0xE220_A839_7B1D_CDAF`; the golden
    /// vectors pin the rest.
    pub fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(SPLITMIX64_GAMMA);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(SPLITMIX64_MIX_1);
        z = (z ^ (z >> 27)).wrapping_mul(SPLITMIX64_MIX_2);
        z ^ (z >> 31)
    }

    /// Returns the next 32-bit word: the **high** half of the next 64-bit word.
    pub fn next_u32(&mut self) -> u32 {
        (self.next_u64() >> 32) as u32
    }

    /// Returns a value in `0..bound` (or `0` when `bound == 0`).
    ///
    /// Uses the low bits of a full 64-bit word and plain modulo. Modulo is
    /// exact integer arithmetic, so the result is identical on every platform;
    /// the slight bias is irrelevant for corpus generation.
    pub fn next_below(&mut self, bound: u32) -> u32 {
        if bound == 0 {
            0
        } else {
            (self.next_u64() % u64::from(bound)) as u32
        }
    }

    /// Returns `true` for an odd word, `false` for an even one.
    pub fn next_bool(&mut self) -> bool {
        self.next_u64() & 1 == 1
    }

    /// The canonical byte encoding of a seed: 8 bytes, little-endian.
    pub fn seed_bytes(seed: u64) -> [u8; 8] {
        seed.to_le_bytes()
    }
}

/// Generates the frozen six-action sequence for `seed`.
pub fn generate_sequence(seed: u64) -> ActionSequence {
    let mut expander = SeedExpander::new(seed);
    generate_sequence_with_rng(|| expander.next_u64(), GENERATED_SEQUENCE_LEN)
}

/// Generates a sequence of `len` actions from a raw 64-bit word stream.
///
/// This is the mapping the golden vectors freeze: each action consumes the
/// words listed in `model/SEED_EXPANSION.md`. It is public so the determinism
/// suite can drive a deliberately perturbed stream through the exact same
/// mapping (see `model/tests/seed_determinism.rs`).
///
/// Every generated action is within the ranges the reference model accepts; the
/// generator never produces floats, time or addresses, so nothing outside the
/// word stream can influence the result.
pub fn generate_sequence_with_rng<F>(mut next_u64: F, len: usize) -> ActionSequence
where
    F: FnMut() -> u64,
{
    let mut actions = Vec::with_capacity(len);
    for _ in 0..len {
        let action = match next_below(&mut next_u64, 10) {
            0 => Action::CreateStream {
                sender_idx: next_below(&mut next_u64, 4) as u8,
                recipient_idx: next_below(&mut next_u64, 4) as u8,
                deposit_amount: 1 + i128::from(next_below(&mut next_u64, 1_000_000_000)),
                start_delay_secs: next_below(&mut next_u64, 86_400),
                duration_secs: 1 + next_below(&mut next_u64, 86_400),
                cancelable: next_flag(&mut next_u64),
            },
            1 => Action::Withdraw {
                stream_id: 1 + u64::from(next_below(&mut next_u64, 50)),
                amount: 1 + i128::from(next_below(&mut next_u64, 1_000_000_000)),
            },
            2 => Action::WithdrawMax {
                stream_id: 1 + u64::from(next_below(&mut next_u64, 50)),
            },
            3 => Action::CancelStream {
                caller_idx: next_below(&mut next_u64, 4) as u8,
                stream_id: 1 + u64::from(next_below(&mut next_u64, 50)),
            },
            4 => Action::TopUp {
                caller_idx: next_below(&mut next_u64, 4) as u8,
                stream_id: 1 + u64::from(next_below(&mut next_u64, 50)),
                amount: 1 + i128::from(next_below(&mut next_u64, 1_000_000_000)),
            },
            5 => Action::SetFeeBps {
                caller_is_gov: next_flag(&mut next_u64),
                new_fee_bps: next_below(&mut next_u64, 101),
            },
            6 => Action::NominateGovernor {
                caller_is_gov: next_flag(&mut next_u64),
                nominee_idx: next_below(&mut next_u64, 4) as u8,
            },
            7 => Action::AcceptGovernor {
                caller_idx: next_below(&mut next_u64, 4) as u8,
            },
            8 => Action::WithdrawTreasury {
                caller_is_gov: next_flag(&mut next_u64),
                recipient_idx: next_below(&mut next_u64, 4) as u8,
                amount: 1 + i128::from(next_below(&mut next_u64, 1_000_000_000)),
            },
            _ => Action::AdvanceTime {
                seconds: next_below(&mut next_u64, 30 * 86_400),
            },
        };
        actions.push(action);
    }
    ActionSequence::new(actions)
}

/// Samples `0..bound` from a raw word stream; `0` when `bound == 0`.
fn next_below<F: FnMut() -> u64>(next_u64: &mut F, bound: u32) -> u32 {
    if bound == 0 {
        0
    } else {
        (next_u64() % u64::from(bound)) as u32
    }
}

/// Samples one bit from a raw word stream.
fn next_flag<F: FnMut() -> u64>(next_u64: &mut F) -> bool {
    next_u64() & 1 == 1
}

/// 1. Create stream and linearly withdraw in increments.
pub fn seed_create_and_linear_withdraw() -> ActionSequence {
    ActionSequence::new(vec![
        Action::CreateStream {
            sender_idx: 0,
            recipient_idx: 1,
            deposit_amount: DEPOSIT,
            start_delay_secs: DAY,
            duration_secs: 10 * DAY,
            cancelable: true,
        },
        Action::AdvanceTime { seconds: 3 * DAY }, // 2 days elapsed of 10
        Action::Withdraw {
            stream_id: 1,
            amount: 2 * DEPOSIT / 10,
        },
        Action::AdvanceTime { seconds: 8 * DAY }, // past end
        Action::Withdraw {
            stream_id: 1,
            amount: 8 * DEPOSIT / 10,
        },
    ])
}

