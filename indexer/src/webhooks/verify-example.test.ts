import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  STREAMPAY_WEBHOOK_TOLERANCE_SEC,
  verifyStreampayWebhook,
} from "./verify-example.js";
import { generateSignatureHeader } from "./hmac.js";

interface WebhookFixture {
  timestamp: number;
  secret: string;
  header: string;
  raw_body: string;
}

const fixturePath = resolve(process.cwd(), "../test_fixtures/webhook-signature.json");
const fixture = JSON.parse(readFileSync(fixturePath, "utf8")) as WebhookFixture;
const rawBody = new TextEncoder().encode(fixture.raw_body);

describe("documented webhook signature verification", () => {
  it("verifies the pinned fixture generated by the real HMAC implementation", () => {
    assert.strictEqual(
      generateSignatureHeader(fixture.secret, fixture.timestamp, fixture.raw_body),
      fixture.header
    );
    assert.strictEqual(
      verifyStreampayWebhook(
        fixture.header,
        rawBody,
        fixture.secret,
        fixture.timestamp,
        STREAMPAY_WEBHOOK_TOLERANCE_SEC
      ),
      true
    );
  });

  it("rejects wrong secrets and tampered raw bodies", () => {
    assert.strictEqual(
      verifyStreampayWebhook(fixture.header, rawBody, "wrong_secret", fixture.timestamp),
      false
    );
    assert.strictEqual(
      verifyStreampayWebhook(
        fixture.header,
        new TextEncoder().encode(fixture.raw_body.replace("evt_fixture_535", "evt_tampered")),
        fixture.secret,
        fixture.timestamp
      ),
      false
    );
  });

  it("rejects stale and future timestamps outside the replay window", () => {
    assert.strictEqual(
      verifyStreampayWebhook(
        fixture.header,
        rawBody,
        fixture.secret,
        fixture.timestamp - STREAMPAY_WEBHOOK_TOLERANCE_SEC - 1
      ),
      false
    );
    assert.strictEqual(
      verifyStreampayWebhook(
        fixture.header,
        rawBody,
        fixture.secret,
        fixture.timestamp + STREAMPAY_WEBHOOK_TOLERANCE_SEC + 1
      ),
      false
    );
  });

  it("rejects malformed and missing signature headers", () => {
    assert.strictEqual(verifyStreampayWebhook("", rawBody, fixture.secret, fixture.timestamp), false);
    assert.strictEqual(
      verifyStreampayWebhook(`t=${fixture.timestamp}`, rawBody, fixture.secret, fixture.timestamp),
      false
    );
    assert.strictEqual(
      verifyStreampayWebhook(
        `t=not-a-time,v1=${"0".repeat(64)}`,
        rawBody,
        fixture.secret,
        fixture.timestamp
      ),
      false
    );
  });

  it("rejects malformed and mismatched signature lengths", () => {
    assert.strictEqual(
      verifyStreampayWebhook(
        `t=${fixture.timestamp},v1=xyz`,
        rawBody,
        fixture.secret,
        fixture.timestamp
      ),
      false
    );
  });

  it("documents the pinned replay fixture and both header and raw-body drift guards", () => {
    const docs = readFileSync(resolve(process.cwd(), "../docs/WEBHOOKS.md"), "utf8");
    assert.match(docs, /Streampay-Signature/);
    assert.match(docs, /\$\{timestamp\}\./);
    assert.match(docs, /300 seconds/);
    assert.match(docs, /raw request body/i);
  });
});
