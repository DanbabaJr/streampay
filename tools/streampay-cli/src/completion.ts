/**
 * Shell completion scripts for bash, zsh, and fish, generated from the command registry.
 * The output is a static script: completing a word never runs node.
 */
import {
  COMMANDS,
  COMPLETION_SHELLS,
  GLOBAL_OPTIONS,
  allOptions,
  type CommandSpec,
  type OptionSpec,
} from "./registry.ts";

export type CompletionShell = (typeof COMPLETION_SHELLS)[number];

const PROGRAM = "streampay";

const flagsOf = (options: readonly OptionSpec[]) => options.map((option) => `--${option.name}`);
const GLOBAL_NAMES = new Set(GLOBAL_OPTIONS.map((option) => option.name));
/** A command's own flags, leaving out ones already offered as global options. */
const ownFlags = (options: readonly OptionSpec[]) => flagsOf(options.filter((option) => !GLOBAL_NAMES.has(option.name)));
const takesValue = (option: OptionSpec) => option.kind !== "flag";

function valueOptions(): OptionSpec[] {
  return allOptions().filter(takesValue);
}

function words(values: readonly string[]): string {
  return values.join(" ");
}

function singleQuote(text: string): string {
  return `'${text.replace(/'/g, "'\\''")}'`;
}

function bash(): string {
  const valueFlags = flagsOf(valueOptions()).join("|");
  const enums = valueOptions().filter((option) => option.kind === "enum");
  const files = valueOptions().filter((option) => option.kind === "file");
  const free = valueOptions().filter((option) => option.kind === "value");
  const globals = words(flagsOf(GLOBAL_OPTIONS));

  const commandCases = COMMANDS.map((command) => {
    if (command.subcommands?.length) {
      const subCases = command.subcommands
        .map((sub) => `        ${sub.name}) opts="$opts ${words(ownFlags(sub.options))}" ;;`)
        .join("\n");
      return [
        `    ${command.name})`,
        `      if [[ -z "$sub" && "$cur" != -* ]]; then`,
        `        COMPREPLY=($(compgen -W "${words(command.subcommands.map((sub) => sub.name))}" -- "$cur"))`,
        "        return 0",
        "      fi",
        `      case "$sub" in`,
        subCases,
        "      esac",
        "      ;;",
      ].join("\n");
    }
    if (command.positional) {
      return [
        `    ${command.name})`,
        `      if [[ -z "$sub" && "$cur" != -* ]]; then`,
        `        COMPREPLY=($(compgen -W "${words(command.positional.values)}" -- "$cur"))`,
        "        return 0",
        "      fi",
        "      ;;",
      ].join("\n");
    }
    const own = ownFlags(command.options);
    return own.length ? `    ${command.name}) opts="$opts ${words(own)}" ;;` : `    ${command.name}) ;;`;
  }).join("\n");

  return `# bash completion for ${PROGRAM}. Generated by \`${PROGRAM} completion bash\`; do not edit.
_${PROGRAM}() {
  local cur prev cmd="" sub="" opts i w
  COMPREPLY=()
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"

  for ((i = 1; i < COMP_CWORD; i++)); do
    w="\${COMP_WORDS[i]}"
    case "$w" in
      ${valueFlags}) ((i++)); continue ;;
      -*) continue ;;
    esac
    if [[ -z "$cmd" ]]; then cmd="$w"; elif [[ -z "$sub" ]]; then sub="$w"; fi
  done

  case "$prev" in
${enums.map((option) => `    --${option.name}) COMPREPLY=($(compgen -W "${words(option.values ?? [])}" -- "$cur")); return 0 ;;`).join("\n")}
    ${flagsOf(files).join("|")}) COMPREPLY=($(compgen -f -- "$cur")); return 0 ;;
    ${flagsOf(free).join("|")}) return 0 ;;
  esac

  opts="${globals}"
  case "$cmd" in
    "")
      if [[ "$cur" != -* ]]; then
        COMPREPLY=($(compgen -W "${words(COMMANDS.map((command) => command.name))}" -- "$cur"))
        return 0
      fi
      ;;
${commandCases}
  esac
  COMPREPLY=($(compgen -W "$opts" -- "$cur"))
}
complete -F _${PROGRAM} ${PROGRAM}
`;
}

function zsh(): string {
  const valueFlags = flagsOf(valueOptions()).join("|");
  const enums = valueOptions().filter((option) => option.kind === "enum");
  const files = valueOptions().filter((option) => option.kind === "file");
  const free = valueOptions().filter((option) => option.kind === "value");
  const globals = words(flagsOf(GLOBAL_OPTIONS));

  const commandCases = COMMANDS.map((command) => {
    if (command.subcommands?.length) {
      const subCases = command.subcommands
        .map((sub) => `        (${sub.name}) opts+=(${words(ownFlags(sub.options))}) ;;`)
        .join("\n");
      return [
        `    (${command.name})`,
        `      if [[ -z $sub && $cur != -* ]]; then`,
        `        compadd -- ${words(command.subcommands.map((sub) => sub.name))}`,
        "        return",
        "      fi",
        "      case $sub in",
        subCases,
        "      esac",
        "      ;;",
      ].join("\n");
    }
    if (command.positional) {
      return [
        `    (${command.name})`,
        `      if [[ -z $sub && $cur != -* ]]; then`,
        `        compadd -- ${words(command.positional.values)}`,
        "        return",
        "      fi",
        "      ;;",
      ].join("\n");
    }
    const own = ownFlags(command.options);
    return own.length ? `    (${command.name}) opts+=(${words(own)}) ;;` : `    (${command.name}) ;;`;
  }).join("\n");

  return `#compdef ${PROGRAM}
# zsh completion for ${PROGRAM}. Generated by \`${PROGRAM} completion zsh\`; do not edit.
_${PROGRAM}() {
  local cur=\${words[CURRENT]} prev=\${words[CURRENT-1]} cmd="" sub="" w i
  local -a opts

  for ((i = 2; i < CURRENT; i++)); do
    w=\${words[i]}
    case $w in
      (${valueFlags}) ((i++)); continue ;;
      (-*) continue ;;
    esac
    if [[ -z $cmd ]]; then cmd=$w; elif [[ -z $sub ]]; then sub=$w; fi
  done

  case $prev in
${enums.map((option) => `    (--${option.name}) compadd -- ${words(option.values ?? [])}; return ;;`).join("\n")}
    (${flagsOf(files).join("|")}) _files; return ;;
    (${flagsOf(free).join("|")}) return 1 ;;
  esac

  opts=(${globals})
  case $cmd in
    ("")
      if [[ $cur != -* ]]; then
        compadd -- ${words(COMMANDS.map((command) => command.name))}
        return
      fi
      ;;
${commandCases}
  esac
  compadd -- $opts
}

if [[ "\${funcstack[1]}" == "_${PROGRAM}" ]]; then
  _${PROGRAM} "$@"
else
  compdef _${PROGRAM} ${PROGRAM}
fi
`;
}

function fishOption(option: OptionSpec, condition?: string): string {
  const parts = [`complete -c ${PROGRAM}`];
  if (condition) parts.push(`-n ${singleQuote(condition)}`);
  parts.push(`-l ${option.name}`);
  if (option.kind === "enum") parts.push(`-x -a ${singleQuote(words(option.values ?? []))}`);
  else if (option.kind === "file") parts.push("-r -F");
  else if (option.kind === "value") parts.push("-x");
  parts.push(`-d ${singleQuote(option.description)}`);
  return parts.join(" ");
}

function fishCommand(command: CommandSpec, condition: string): string {
  return `complete -c ${PROGRAM} -n ${singleQuote(condition)} -f -a ${command.name} -d ${singleQuote(command.description)}`;
}

function fish(): string {
  const lines = [
    `# fish completion for ${PROGRAM}. Generated by \`${PROGRAM} completion fish\`; do not edit.`,
    `function __${PROGRAM}_positionals`,
    "    set -l tokens (commandline -opc)",
    "    set -e tokens[1]",
    "    set -l skip 0",
    "    for t in $tokens",
    "        if test $skip -eq 1",
    "            set skip 0",
    "            continue",
    "        end",
    "        switch $t",
    `            case ${flagsOf(valueOptions()).join(" ")}`,
    "                set skip 1",
    "            case '-*'",
    "            case '*'",
    "                echo $t",
    "        end",
    "    end",
    "end",
    "",
    `function __${PROGRAM}_depth`,
    `    test (count (__${PROGRAM}_positionals)) -eq $argv[1]`,
    "end",
    "",
    `function __${PROGRAM}_is`,
    `    set -l p (__${PROGRAM}_positionals)`,
    "    for i in (seq (count $argv))",
    "        test \"$p[$i]\" = \"$argv[$i]\"; or return 1",
    "    end",
    "end",
    "",
    `complete -c ${PROGRAM} -f`,
    "",
    "# Global options",
    ...GLOBAL_OPTIONS.map((option) => fishOption(option)),
    "",
    "# Commands",
    ...COMMANDS.map((command) => fishCommand(command, `__${PROGRAM}_depth 0`)),
  ];

  for (const command of COMMANDS) {
    const scoped: string[] = [];
    for (const option of command.options) {
      scoped.push(fishOption(option, `__${PROGRAM}_is ${command.name}`));
    }
    for (const sub of command.subcommands ?? []) {
      scoped.push(fishCommand(sub, `__${PROGRAM}_is ${command.name}; and __${PROGRAM}_depth 1`));
      for (const option of sub.options) {
        scoped.push(fishOption(option, `__${PROGRAM}_is ${command.name} ${sub.name}`));
      }
    }
    if (command.positional) {
      scoped.push(
        `complete -c ${PROGRAM} -n ${singleQuote(`__${PROGRAM}_is ${command.name}; and __${PROGRAM}_depth 1`)} -f -a ${singleQuote(words(command.positional.values))}`
      );
    }
    if (scoped.length) lines.push("", `# ${command.name}`, ...scoped);
  }
  return `${lines.join("\n")}\n`;
}

export function isCompletionShell(value: string | undefined): value is CompletionShell {
  return (COMPLETION_SHELLS as readonly string[]).includes(value ?? "");
}

export function completionScript(shell: CompletionShell): string {
  switch (shell) {
    case "bash":
      return bash();
    case "zsh":
      return zsh();
    case "fish":
      return fish();
  }
}
