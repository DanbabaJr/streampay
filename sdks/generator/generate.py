#!/usr/bin/env python3
"""Generate the TypeScript StreamPay client from the canonical spec.

The input is ``sdks/spec/streampay.spec.json`` (derived from the Rust contract
by ``check_contract_surface.py``) plus the canonical error catalog in
``frontend/lib/errors.ts``. This script is deterministic, so ``--check`` is a
valid CI gate: regeneration must be a no-op.

Only the TypeScript target lives here today. The Rust and Python SDKs were
split out of this change and will add their own emitters alongside their
packages; keeping the language targets explicit avoids a generator that
silently claims coverage it does not have.

Usage
  python3 sdks/generator/generate.py           # write generated files
  python3 sdks/generator/generate.py --check   # fail if outputs are stale
"""
from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_contract_surface import fingerprint  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SPEC_PATH = ROOT / "sdks" / "spec" / "streampay.spec.json"
CATALOG_PATH = ROOT / "frontend" / "lib" / "errors.ts"
TS_SRC = ROOT / "sdks" / "typescript" / "src"

SPEC = json.loads(SPEC_PATH.read_text())
FINGERPRINT = fingerprint(SPEC)

HEADER = (
    "// @generated by sdks/generator/generate.py from "
    "sdks/spec/streampay.spec.json (sha256:{fingerprint}).\n"
    "// Do not edit by hand: change the spec, then regenerate.\n"
)


def camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(part.title() for part in parts[1:])


def pascal(name: str) -> str:
    return "".join(part.title() for part in name.split("_"))


def jsdoc(doc: str, indent: str = "") -> str:
    if not doc:
        return ""
    lines = [line.rstrip() for line in doc.splitlines() if line.strip()]
    body = "\n".join(f"{indent} * {line.replace('*/', '* /')}" for line in lines)
    return f"{indent}/**\n{body}\n{indent} */\n"


def enum_has_payload(enum: dict) -> bool:
    """True when any variant carries values (a Rust tuple variant).

    soroban-sdk encodes every ``#[contracttype]`` enum as a vector: the variant
    name as a ``Symbol`` followed by the variant's values. Unit variants (and
    all variants of an enum with no payloads) are a one-element vector.
    """
    return any(case.get("types") for case in enum["cases"])


# --------------------------------------------------------------------------- #
# Type mapping                                                                #
# --------------------------------------------------------------------------- #


def value_type(t: object) -> str:
    """TypeScript type of a decoded value."""
    if isinstance(t, dict):
        if "vec" in t:
            return f"{value_type(t['vec'])}[]"
        if "option" in t:
            return f"{value_type(t['option'])} | null"
        if "result" in t:
            return (
                f"({{ ok: {value_type(t['result']['ok'])} }} | "
                "{ error: StreamErrorName })"
            )
        raise ValueError(f"unknown IR type {t!r}")
    table = {
        "address": "string",
        "bool": "boolean",
        "i32": "number",
        "u32": "number",
        "i128": "bigint",
        "u128": "bigint",
        "u64": "bigint",
        "string": "string",
        "symbol": "string",
        "bytes32": "Bytes",
        "bytes64": "Bytes",
        "void": "void",
    }
    if t in table:
        return table[t]
    return str(t)  # named struct or enum


def input_type(t: object) -> str:
    """TypeScript type accepted for an argument or struct field."""
    if isinstance(t, dict):
        if "vec" in t:
            return f"{input_type(t['vec'])}[]"
        if "option" in t:
            return f"{input_type(t['option'])} | null"
        if "result" in t:
            return value_type(t)
        raise ValueError(f"unknown IR type {t!r}")
    if t == "i128" or t == "u128":
        return "Int128"
    if t == "u64":
        return "U64"
    if t == "u32" or t == "i32":
        return "U32"
    return value_type(t)


def type_label(t: object) -> str:
    """Compact type string carried in the generated FUNCTIONS metadata."""
    if isinstance(t, dict):
        if "vec" in t:
            return "vec:" + type_label(t["vec"])
        if "option" in t:
            return "option:" + type_label(t["option"])
        if "result" in t:
            return "result:" + type_label(t["result"]["ok"])
        raise ValueError(f"unknown IR type {t!r}")
    return str(t)


def encode_expr(t: object, expr: str, label: str) -> str:
    """An expression producing an xdr.ScVal from a typed value."""
    if isinstance(t, dict):
        if "vec" in t:
            inner = encode_expr(t["vec"], "item", f"{label}[index]")
            return (
                f"xdr.ScVal.scvVec(({expr}).map((item, index) => {inner}))"
            )
        if "option" in t:
            inner = encode_expr(t["option"], expr, label)
            return f"(({expr}) == null ? xdr.ScVal.scvVoid() : {inner})"
        if "result" in t:
            raise ValueError("Result values are return-only; cannot encode")
        raise ValueError(f"unknown IR type {t!r}")
    if t == "address":
        return f"addressToScVal({expr})"
    if t in ("i128", "u128"):
        return f'nativeToScVal(asBigInt({expr}, "{label}"), {{ type: "{t}" }})'
    if t == "u64":
        return f'nativeToScVal(asBigInt({expr}, "{label}"), {{ type: "u64" }})'
    if t in ("u32", "i32"):
        return f'nativeToScVal(asNumber({expr}, "{label}"), {{ type: "{t}" }})'
    if t == "bool":
        return f"nativeToScVal({expr})"
    if t == "string":
        return f'nativeToScVal({expr}, {{ type: "string" }})'
    if t == "symbol":
        return f'nativeToScVal({expr}, {{ type: "symbol" }})'
    if t == "bytes32":
        return f'nativeToScVal(asBytes({expr}, "{label}", 32), {{ type: "bytes" }})'
    if t == "bytes64":
        return f'nativeToScVal(asBytes({expr}, "{label}", 64), {{ type: "bytes" }})'
    if t == "void":
        return f"(void {expr}, xdr.ScVal.scvVoid())"
    return f"encode{t}({expr})"


def decode_expr(t: object, expr: str, label: str) -> str:
    """An expression decoding a *native* value (from scValToNative)."""
    if isinstance(t, dict):
        if "vec" in t:
            inner = decode_expr(t["vec"], "item", f"{label}[index]")
            return (
                f"asArray({expr}, \"{label}\").map((item, index) => {inner})"
            )
        if "option" in t:
            inner = decode_expr(t["option"], expr, label)
            return f"(({expr}) == null ? null : {inner})"
        if "result" in t:
            raise ValueError("Result values are decoded from ScVal, not native")
        raise ValueError(f"unknown IR type {t!r}")
    if t in ("address", "string", "symbol"):
        return f'asString({expr}, "{label}")'
    if t in ("i128", "u128", "u64"):
        return f'asBigInt({expr}, "{label}")'
    if t in ("u32", "i32"):
        return f'asNumber({expr}, "{label}")'
    if t == "bool":
        return f'asBool({expr}, "{label}")'
    if t == "bytes32":
        return f'asBytes({expr}, "{label}", 32)'
    if t == "bytes64":
        return f'asBytes({expr}, "{label}", 64)'
    if t == "void":
        return "undefined"
    return f"decode{t}({expr})"


# --------------------------------------------------------------------------- #
# Error catalog                                                               #
# --------------------------------------------------------------------------- #


def load_error_catalog() -> list[tuple[int, str]]:
    """Read the canonical catalog generated from the contract error surface.

    The SDK must not keep a second error table: the codes and names come from
    ``frontend/lib/errors.ts``, which CI already gates against
    ``contracts/streaming-payments/src/errors.rs``.
    """
    text = CATALOG_PATH.read_text()
    entries = [
        (int(code), name)
        for code, name in re.findall(
            r"^\s*(\d+):\s*\{\s*code:\s*\d+,\s*name:\s*\"(\w+)\"",
            text,
            re.MULTILINE,
        )
    ]
    if not entries:
        raise ValueError(f"could not read the error catalog from {CATALOG_PATH}")
    if len({code for code, _ in entries}) != len(entries):
        raise ValueError("duplicate error codes in the catalog")
    return sorted(entries)


# --------------------------------------------------------------------------- #
# generated.ts                                                                #
# --------------------------------------------------------------------------- #


def generate_generated_ts() -> str:
    errors = load_error_catalog()
    lines: list[str] = [HEADER.format(fingerprint=FINGERPRINT), ""]
    lines += [
        'import { Address, StrKey, nativeToScVal, scValToNative, xdr } from "@stellar/stellar-sdk";',
        "",
        f'export const SPEC_FINGERPRINT = "{FINGERPRINT}";',
        f'export const CONTRACT_VERSION = "{SPEC["contract"]["version"]}";',
    ]
    for name, constant in SPEC["constants"].items():
        lines.append(f"export const {name} = {constant['value']};")
    lines.append("")

    lines.append("/** Contract method names, e.g. `METHODS.createStream`. */")
    lines.append("export const METHODS = {")
    for function in SPEC["functions"]:
        lines.append(f'  {camel(function["name"])}: "{function["name"]}",')
    lines.append("} as const;")
    lines.append("")

    lines += [
        "export type Int128 = bigint | string;",
        "export type U64 = bigint | number | string;",
        "export type U32 = number;",
        "export type Bytes = Uint8Array;",
        "",
    ]

    for enum in SPEC["enums"]:
        lines.append(jsdoc(enum.get("doc", "")).rstrip())
        if enum_has_payload(enum):
            lines.append(f"export type {enum['name']} =")
            for index, case in enumerate(enum["cases"]):
                suffix = ";" if index == len(enum["cases"]) - 1 else ""
                values = ", ".join(input_type(t) for t in case.get("types", []))
                lines.append(
                    f'  | {{ type: "{case["name"]}"; values: [{values}] }}{suffix}'
                )
        else:
            union = " | ".join(f'"{case["name"]}"' for case in enum["cases"])
            lines.append(f"export type {enum['name']} = {union};")
        lines.append("")

    for struct in SPEC["structs"]:
        lines.append(jsdoc(struct.get("doc", "")).rstrip())
        lines.append(f"export interface {struct['name']} {{")
        for field in struct["fields"]:
            lines.append(f"  /** {field['doc'].replace(chr(10), ' ')} */" if field.get("doc") else "")
            lines.append(f"  {camel(field['name'])}: {value_type(field['type'])};")
        lines.append("}")
        lines.append("")

    for function in SPEC["functions"]:
        if not function["args"]:
            continue
        lines.append(jsdoc(function.get("doc", "")).rstrip())
        lines.append(f"export interface {pascal(function['name'])}Args {{")
        for arg in function["args"]:
            if arg.get("doc"):
                lines.append(f"  /** {arg['doc'].replace(chr(10), ' ')} */")
            lines.append(f"  {camel(arg['name'])}: {input_type(arg['type'])};")
        lines.append("}")
        lines.append("")

    lines += [
        "// --------------------------------------------------------------------- //",
        "// Runtime helpers                                                        //",
        "// --------------------------------------------------------------------- //",
        "",
        "function asNative(value: xdr.ScVal): unknown {",
        "  return scValToNative(value) as unknown;",
        "}",
        "",
        "function asBigInt(value: unknown, label: string): bigint {",
        "  if (typeof value === \"bigint\") return value;",
        "  if (typeof value === \"number\" && Number.isInteger(value)) return BigInt(value);",
        "  if (typeof value === \"string\" && /^-?\\d+$/.test(value)) return BigInt(value);",
        "  throw new Error(`${label}: expected an integer, got ${typeof value}`);",
        "}",
        "",
        "function asNumber(value: unknown, label: string): number {",
        "  if (typeof value === \"number\" && Number.isInteger(value)) return value;",
        "  if (typeof value === \"bigint\") return Number(value);",
        "  throw new Error(`${label}: expected a number, got ${typeof value}`);",
        "}",
        "",
        "function asString(value: unknown, label: string): string {",
        "  if (typeof value !== \"string\") throw new Error(`${label}: expected a string`);",
        "  return value;",
        "}",
        "",
        "function asBool(value: unknown, label: string): boolean {",
        "  if (typeof value !== \"boolean\") throw new Error(`${label}: expected a bool`);",
        "  return value;",
        "}",
        "",
        "function asBytes(value: unknown, label: string, length: number): Uint8Array {",
        "  if (!(value instanceof Uint8Array)) throw new Error(`${label}: expected bytes`);",
        "  if (value.length !== length) {",
        "    throw new Error(`${label}: expected ${length} bytes, got ${value.length}`);",
        "  }",
        "  return value;",
        "}",
        "",
        "function asArray(value: unknown, label: string): unknown[] {",
        "  if (!Array.isArray(value)) throw new Error(`${label}: expected an array`);",
        "  return value;",
        "}",
        "",
        "export function addressToScVal(value: string): xdr.ScVal {",
        "  return nativeToScVal(new Address(value), { type: \"address\" });",
        "}",
        "",
        "function structScVal(entries: Array<[string, xdr.ScVal]>): xdr.ScVal {",
        "  const sorted = [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));",
        "  return xdr.ScVal.scvMap(",
        "    sorted.map(([key, val]) => new xdr.ScMapEntry({ key: xdr.ScVal.scvSymbol(key), val }))",
        "  );",
        "}",
        "",
    ]

    for enum in SPEC["enums"]:
        name = enum["name"]
        payload = enum_has_payload(enum)
        lines.append(f"export function encode{name}(value: {name}): xdr.ScVal {{")
        lines.append("  switch (value.type) {" if payload else "  switch (value) {")
        for case in enum["cases"]:
            tag = json.dumps(case["name"])
            lines.append(f"    case {tag}:")
            if payload:
                entries = [
                    encode_expr(t, f"value.values[{index}]", f"{name}.{case['name']}[{index}]")
                    for index, t in enumerate(case.get("types", []))
                ]
                lines.append("      return xdr.ScVal.scvVec([")
                lines.append(f"        xdr.ScVal.scvSymbol({tag}),")
                for entry in entries:
                    lines.append(f"        {entry},")
                lines.append("      ]);")
            else:
                lines.append(
                    f"      return xdr.ScVal.scvVec([xdr.ScVal.scvSymbol({tag})]);"
                )
        lines.append("    default:")
        if payload:
            # The switch is exhaustive over the union, so `value` narrows to
            # `never` here; widen it to report the offending tag.
            lines.append(
                f"      throw new Error(`invalid {name} type: "
                "${String((value as { type?: unknown }).type)}`);"
            )
        else:
            lines.append(f"      throw new Error(`invalid {name}: ${{String(value)}}`);")
        lines.append("  }")
        lines.append("}")
        lines.append("")
        lines.append(f"export function decode{name}(value: unknown): {name} {{")
        lines.append(f'  const items = asArray(value, "{name}");')
        lines.append(f'  switch (asString(items[0], "{name} variant")) {{')
        for case in enum["cases"]:
            tag = json.dumps(case["name"])
            lines.append(f"    case {tag}:")
            if payload:
                values = ", ".join(
                    decode_expr(t, f"items[{index + 1}]", f"{name}.{case['name']}[{index}]")
                    for index, t in enumerate(case.get("types", []))
                )
                lines.append(f"      return {{ type: {tag}, values: [{values}] }};")
            else:
                lines.append(f"      return {tag};")
        lines.append("    default:")
        lines.append(
            f"      throw new Error(`unknown {name} variant: ${{String(items[0])}}`);"
        )
        lines.append("  }")
        lines.append("}")
        lines.append("")

    for struct in SPEC["structs"]:
        lines.append(f"export function encode{struct['name']}(value: {struct['name']}): xdr.ScVal {{")
        lines.append("  return structScVal([")
        for field in struct["fields"]:
            entry = encode_expr(field["type"], f"value.{camel(field['name'])}", f"{struct['name']}.{field['name']}")
            lines.append(f'    ["{field["name"]}", {entry}],')
        lines.append("  ]);")
        lines.append("}")
        lines.append("")
        lines.append(f"export function decode{struct['name']}(value: unknown): {struct['name']} {{")
        lines.append("  if (value === null || typeof value !== \"object\") {")
        lines.append(f'    throw new Error("decode{struct["name"]}: expected a map");')
        lines.append("  }")
        lines.append("  const native = value as Record<string, unknown>;")
        lines.append("  return {")
        for field in struct["fields"]:
            entry = decode_expr(field["type"], f"native.{field['name']}", f"{struct['name']}.{field['name']}")
            lines.append(f"    {camel(field['name'])}: {entry},")
        lines.append("  };")
        lines.append("}")
        lines.append("")

    for function in SPEC["functions"]:
        name = function["name"]
        args_type = pascal(name) + "Args"
        if function["args"]:
            lines.append(
                f"export function encode{pascal(name)}Args(args: {args_type}): xdr.ScVal[] {{"
            )
            lines.append("  return [")
            for arg in function["args"]:
                entry = encode_expr(
                    arg["type"], f"args.{camel(arg['name'])}", f"{name}.{arg['name']}"
                )
                lines.append(f"    {entry},")
            lines.append("  ];")
            lines.append("}")
        else:
            lines.append(
                f"export function encode{pascal(name)}Args(): xdr.ScVal[] {{"
            )
            lines.append("  return [];")
            lines.append("}")
        lines.append("")

        returns = function["returns"]
        lines.append(
            f"export function decode{pascal(name)}Result(value: xdr.ScVal): {value_type(returns)} {{"
        )
        if returns == "void":
            lines.append("  void value;")
            lines.append("  return undefined;")
        elif isinstance(returns, dict) and "result" in returns:
            ok = returns["result"]["ok"]
            # Ok values are the raw inner ScVal; Err is an ScVal error.
            lines.append(
                f'  return decodeResultVec(value, (item) => {decode_expr(ok, "asNative(item)", name + " result")}, "{name}");'
            )
        elif (
            isinstance(returns, dict)
            and "vec" in returns
            and isinstance(returns["vec"], dict)
            and "result" in returns["vec"]
        ):
            ok = returns["vec"]["result"]["ok"]
            lines.append(
                f'  return decodeResultVec(value, (item) => {decode_expr(ok, "asNative(item)", name + " result")}, "{name}");'
            )
        elif isinstance(returns, dict) and "vec" in returns:
            inner = decode_expr(
                returns["vec"], "item", f"{name} result[index]"
            )
            lines.append(
                f'  return asArray(asNative(value), "{name} result").map((item, index) => {inner});'
            )
        elif isinstance(returns, dict) and "option" in returns:
            inner = decode_expr(returns["option"], "asNative(value)", f"{name} result")
            lines.append(f"  return asNative(value) == null ? null : {inner};")
        else:
            entry = decode_expr(returns, "asNative(value)", f"{name} result")
            lines.append(f"  return {entry};")
        lines.append("}")
        lines.append("")

    # Events.
    lines += [
        "export interface EventBase {",
        "  contractId: string;",
        "}",
        "",
    ]
    for event in SPEC["events"]:
        lines.append(jsdoc(event.get("doc", "")).rstrip())
        lines.append(f"export interface {event['name']}Event extends EventBase {{")
        lines.append(f'  type: "{event["name"]}";')
        for field in event["topicFields"] + event["dataFields"]:
            if field.get("doc"):
                lines.append(f"  /** {field['doc'].replace(chr(10), ' ')} */")
            lines.append(f"  {camel(field['name'])}: {value_type(field['type'])};")
        lines.append("}")
        lines.append("")
    variants = " | ".join(f"{event['name']}Event" for event in SPEC["events"])
    lines.append(f"export type StreamPayEvent = {variants};")
    lines.append("")

    lines += [
        "function eventContractId(event: xdr.ContractEvent): string {",
        "  type ContractIdLike = { value: Uint8Array };",
        "  const raw = (event as unknown as { contractId?: ContractIdLike }).contractId;",
        "  if (!raw) throw new Error(\"event has no contract id\");",
        "  return StrKey.encodeContract(Buffer.from(raw.value));",
        "}",
        "",
        "function topicValue(topics: xdr.ScVal[], index: number, name: string): xdr.ScVal {",
        "  const value = topics[index];",
        "  if (value === undefined) throw new Error(`event ${name} is missing topic ${index}`);",
        "  return value;",
        "}",
        "",
        "function dataValue(data: Record<string, unknown>, name: string): unknown {",
        "  if (!(name in data)) throw new Error(`event data is missing field ${name}`);",
        "  return data[name];",
        "}",
        "",
        "/** Extracts a `StreamError` code from simulation/submission error text. */",
        "export function contractErrorFromMessage(message: string): number | undefined {",
        "  const match = message.match(/Error\\(Contract, #(\\d+)\\)/);",
        "  return match ? Number(match[1]) : undefined;",
        "}",
        "",
    ]

    lines.append("/** Decodes a StreamPay contract event; `null` for foreign events. */")
    lines.append("export function decodeStreamPayEvent(event: xdr.ContractEvent): StreamPayEvent | null {")
    lines.append("  const type = (event as unknown as { type?: { name?: string } }).type;")
    lines.append("  if (type?.name !== \"contract\") return null;")
    lines.append("  const body = (event as unknown as { body?: { v0?: { topics: xdr.ScVal[]; data: xdr.ScVal } } }).body;")
    lines.append("  if (!body?.v0) throw new Error(\"unsupported ContractEvent body\");")
    lines.append("  const topics = body.v0.topics;")
    lines.append("  const name = asString(asNative(topicValue(topics, 0, \"<unknown>\")), \"event name\");")
    lines.append("  const contractId = eventContractId(event);")
    lines.append("  const data = asNative(body.v0.data) as Record<string, unknown>;")
    lines.append("  switch (name) {")
    for event in SPEC["events"]:
        lines.append(f'    case "{event["topic"]}": {{')
        lines.append("      return {")
        lines.append(f'        type: "{event["name"]}",')
        lines.append("        contractId,")
        index = 1
        for field in event["topicFields"]:
            entry = decode_expr(
                field["type"],
                f"asNative(topicValue(topics, {index}, {json.dumps(event['topic'])}))",
                f"{event['name']}.{field['name']}",
            )
            lines.append(f"        {camel(field['name'])}: {entry},")
            index += 1
        for field in event["dataFields"]:
            entry = decode_expr(
                field["type"],
                f"dataValue(data, {json.dumps(field['name'])})",
                f"{event['name']}.{field['name']}",
            )
            lines.append(f"        {camel(field['name'])}: {entry},")
        lines.append("      };")
        lines.append("    }")
    lines.append("    default:")
    lines.append("      return null;")
    lines.append("  }")
    lines.append("}")
    lines.append("")

    # Result-vector helper (batch entry results).
    lines += [
        "/** Decodes a Vec<Result<T, StreamError>> (batch per-entry results). */",
        "function decodeResultVec<T>(",
        "  value: xdr.ScVal,",
        "  decodeOk: (value: xdr.ScVal) => T,",
        "  label: string",
        "): Array<{ ok: T } | { error: StreamErrorName }> {",
        "  const tagged = value as unknown as { type?: string; vec?: xdr.ScVal[] };",
        "  if (tagged.type !== \"scvVec\" || !Array.isArray(tagged.vec)) {",
        "    throw new Error(`${label}: expected a vec`);",
        "  }",
        "  return tagged.vec.map((item) => {",
        "    const errorValue = item as unknown as {",
        "      type?: string;",
        "      error?: { type?: string; contractCode?: number };",
        "    };",
        "    if (errorValue.type === \"scvError\") {",
        "      const code = errorValue.error?.contractCode;",
        "      const name = typeof code === \"number\" ? contractErrorName(code) : undefined;",
        "      return { error: (name ?? \"UnknownContractError\") as StreamErrorName };",
        "    }",
        "    return { ok: decodeOk(item) };",
        "  });",
        "}",
        "",
    ]

    # Error catalog (the one canonical table).
    lines.append("export type StreamErrorName =")
    for index, (_, name) in enumerate(errors):
        suffix = ";" if index == len(errors) - 1 else ""
        lines.append(f'  | "{name}"{suffix}')
    lines.append("")
    lines.append("export const CONTRACT_ERRORS: Readonly<Record<number, StreamErrorName>> = {")
    for code, name in errors:
        lines.append(f'  {code}: "{name}",')
    lines.append("};")
    lines.append("")
    lines.append("export function contractErrorName(code: number): StreamErrorName | undefined {")
    lines.append("  return CONTRACT_ERRORS[code];")
    lines.append("}")
    lines.append("")

    lines.append("export interface FunctionSpec {")
    lines.append("  name: string;")
    lines.append("  argNames: readonly string[];")
    lines.append("  argTypes: readonly string[];")
    lines.append("  returnType: string;")
    lines.append("  mutating: boolean;")
    lines.append("}")
    lines.append("")
    lines.append("export const FUNCTIONS: readonly FunctionSpec[] = [")
    for function in SPEC["functions"]:
        arg_names = ", ".join(json.dumps(arg["name"]) for arg in function["args"])
        arg_types = ", ".join(
            json.dumps(type_label(arg["type"])) for arg in function["args"]
        )
        lines.append("  {")
        lines.append(f"    name: {json.dumps(function['name'])},")
        lines.append(f"    argNames: [{arg_names}],")
        lines.append(f"    argTypes: [{arg_types}],")
        lines.append(f"    returnType: {json.dumps(type_label(function['returns']))},")
        lines.append(f"    mutating: {'true' if function['mutating'] else 'false'},")
        lines.append("  },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


