def outputs() -> dict[Path, str]:
    """Generated files for every language package present in this checkout.

    The shared spec+generator PR has no language package, so it has no
    generated outputs to check. A language PR adds its package (and its
    emitter) and the same ``--check`` gate then covers it.
    """
    targets: dict[Path, str] = {}
    if TS_SRC.parent.is_dir():
        targets[TS_SRC / "generated.ts"] = generate_generated_ts()
        targets[TS_SRC / "methods.ts"] = generate_methods_ts()
    return targets


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when the committed files differ from the generator output",
    )
    args = parser.parse_args()

    stale = False
    for path, content in outputs().items():
        if args.check:
            existing = path.read_text() if path.exists() else ""
            if existing != content:
                stale = True
                diff = difflib.unified_diff(
                    existing.splitlines(keepends=True),
                    content.splitlines(keepends=True),
                    fromfile=str(path),
                    tofile=str(path) + " (generated)",
                )
                sys.stderr.writelines(list(diff)[:80])
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if args.check and stale:
        print(
            "generated TypeScript is stale; run `python3 sdks/generator/generate.py`",
            file=sys.stderr,
        )
        return 1
    if args.check:
        print(
            f"generated clients match the spec: {len(SPEC['functions'])} operations, "
            f"{len(outputs())} file(s), sha256 {FINGERPRINT[:12]}…"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
