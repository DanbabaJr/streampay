def generate_struct(struct: dict) -> list[str]:
    name = struct["name"]
    lines = rustdoc(struct.get("doc", ""))
    lines.append("#[derive(Clone, Debug, PartialEq, Eq)]")
    lines.append(f"pub struct {name} {{")
    for field in struct["fields"]:
        lines += rustdoc(field.get("doc", ""), "    ")
        lines.append(f"    pub {field['name']}: {value_type(field['type'])},")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {name} {{")
    lines.append("    /// Decodes the contract's map encoding of this struct.")
    lines.append(f"    pub fn from_scval(value: &ScVal) -> Result<Self, crate::DecodeError> {{")
    lines.append(f"        let fields = crate::struct_fields(value, {quote(name)})?;")
    lines.append("        Ok(Self {")
    for field in struct["fields"]:
        lines.append(f"            {field['name']}: {field_expr(field, name)},")
    lines.append("        })")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return lines


def generate_enum(enum: dict) -> list[str]:
    name = enum["name"]
    cases = enum["cases"]
    lines = rustdoc(enum.get("doc", ""))
    lines.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    lines.append(f"pub enum {name} {{")
    for case in cases:
        lines += rustdoc(case.get("doc", ""), "    ")
        lines.append(f"    {case['name']},")
    lines.append("}")
    lines.append("")
    names = ", ".join(f"Self::{case['name']}" for case in cases)
    lines.append(f"impl {name} {{")
    lines.append("    pub const ALL: &'static [Self] = &[" + names + "];")
    lines.append("")
    lines.append("    /// The enum's canonical case name.")
    lines.append("    pub fn name(self) -> &'static str {")
    lines.append("        match self {")
    for case in cases:
        lines.append(f"            Self::{case['name']} => {quote(case['name'])},")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Decodes the contract's wire encoding of this enum.")
    lines.append(f"    pub fn from_scval(value: &ScVal) -> Result<Self, crate::DecodeError> {{")
    if enum["encoding"] == "u32":
        lines.append(f"        let code = crate::scval_u32(value, {quote(name)})?;")
        lines.append("        match code {")
        for case in cases:
            lines.append(f"            {case['value']} => Ok(Self::{case['name']}),")
        lines.append(
            "            other => Err(crate::DecodeError::unknown_case("
            f"{quote(name)}, &other.to_string())),"
        )
        lines.append("        }")
    else:
        lines.append("        let tag = match value {")
        lines.append("            ScVal::Vec(Some(items)) if items.len() == 1 => match &items[0] {")
        lines.append("                ScVal::Symbol(symbol) => symbol.0.to_utf8_string_lossy(),")
        lines.append(
            "                other => return Err(crate::DecodeError::unexpected("
            f"{quote(name)}, \"symbol\", other)),"
        )
        lines.append("            },")
        lines.append("            ScVal::Symbol(symbol) => symbol.0.to_utf8_string_lossy(),")
        lines.append(
            "            other => return Err(crate::DecodeError::unexpected("
            f"{quote(name)}, \"symbol or [symbol]\", other)),"
        )
        lines.append("        };")
        lines.append("        match tag.as_str() {")
        for case in cases:
            lines.append(f"            {quote(case['name'])} => Ok(Self::{case['name']}),")
        lines.append(
            "            other => Err(crate::DecodeError::unknown_case("
            f"{quote(name)}, other)),"
        )
        lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return lines


def generate_union(union: dict) -> list[str]:
    name = union["name"]
    lines = rustdoc(union.get("doc", ""))
    lines.append("#[derive(Clone, Debug, PartialEq, Eq)]")
    lines.append(f"pub enum {name} {{")
    for case in union["cases"]:
        payload = None
        if case["types"]:
            payload = ", ".join(value_type(t) for t in case["types"])
        lines += rustdoc(case.get("doc", ""), "    ")
        suffix = f"({payload})" if payload is not None else ""
        lines.append(f"    {case['name']}{suffix},")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {name} {{")
    lines.append("    /// Decodes the contract's `Vec[Symbol(case), payload…]` encoding.")
    lines.append(f"    pub fn from_scval(value: &ScVal) -> Result<Self, crate::DecodeError> {{")
    lines.append("        let items = match value {")
    lines.append("            ScVal::Vec(Some(items)) => items,")
    lines.append(
        "            other => return Err(crate::DecodeError::unexpected("
        f"{quote(name)}, \"vec\", other)),"
    )
    lines.append("        };")
    lines.append("        let tag = match items.first() {")
    lines.append("            Some(ScVal::Symbol(symbol)) => symbol.0.to_utf8_string_lossy(),")
    lines.append(
        "            Some(other) => return Err(crate::DecodeError::unexpected("
        f"{quote(name + '.variant')}, \"symbol\", other)),"
    )
    lines.append(
        "            None => return Err(crate::DecodeError::missing("
        f"{quote(name + '.variant')})),"
    )
    lines.append("        };")
    lines.append("        match tag.as_str() {")
    for case in union["cases"]:
        expected = len(case["types"]) + 1
        lines.append(f"            {quote(case['name'])} => {{")
        lines.append(f"                if items.len() != {expected} {{")
        lines.append(
            "                    return Err(crate::DecodeError::union_arity("
            f"{quote(name + '.' + case['name'])}, {expected}, items.len()));"
        )
        lines.append("                }")
        if case["types"]:
            values = []
            for index, case_type in enumerate(case["types"]):
                context = f"{name}.{case['name']}[{index}]"
                values.append(
                    decode_expr(case_type, f"&items[{index + 1}]", context) + "?"
                )
            lines.append(f"                Ok(Self::{case['name']}({', '.join(values)}))")
        else:
            lines.append(f"                Ok(Self::{case['name']})")
        lines.append("            }")
    lines.append(
        "            other => Err(crate::DecodeError::unknown_case("
        f"{quote(name)}, other)),"
    )
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return lines


def generate_error_enum() -> list[str]:
    lines = [
        "/// Contract error codes, read from the canonical catalog",
        "/// (`frontend/lib/errors.ts`), never restated by an SDK.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "#[repr(u32)]",
        "pub enum StreamError {",
    ]
    for code, name in ERRORS:
        lines.append(f"    {name} = {code},")
    lines.append("}")
    lines.append("")
    lines.append("impl StreamError {")
    lines.append("    pub const ALL: &'static [Self] = &[")
    for _, name in ERRORS:
        lines.append(f"        Self::{name},")
    lines.append("    ];")
    lines.append("")
    lines.append("    /// The on-chain contract error code.")
    lines.append("    pub fn code(self) -> u32 {")
    lines.append("        self as u32")
    lines.append("    }")
    lines.append("")
    lines.append("    /// The catalog name, matching the vector canonical form.")
    lines.append("    pub fn name(self) -> &'static str {")
    lines.append("        match self {")
    for _, name in ERRORS:
        lines.append(f"            Self::{name} => {quote(name)},")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Looks up a contract error code.")
    lines.append("    pub fn from_code(code: u32) -> Option<Self> {")
    lines.append("        match code {")
    for code, name in ERRORS:
        lines.append(f"            {code} => Some(Self::{name}),")
    lines.append("            _ => None,")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("impl core::fmt::Display for StreamError {")
    lines.append("    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {")
    lines.append('        write!(formatter, "{} ({})", self.name(), self.code())')
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("impl std::error::Error for StreamError {}")
    lines.append("")
    return lines


def generate_args(function: dict) -> list[str]:
    name = function["name"]
    params = ", ".join(
        f"{arg['name']}: {arg_type(arg['type'])}" for arg in function["args"]
    )
    lines = rustdoc(function.get("doc", ""))
    lines.append(
        f"pub fn {name}_args({params}) -> Result<Vec<ScVal>, EncodeError> {{"
    )
    if function["args"]:
        lines.append("    Ok(vec![")
        for arg in function["args"]:
            lines.append(f"        {encode_expr(arg['type'], arg['name'])},")
        lines.append("    ])")
    else:
        lines.append("    Ok(Vec::new())")
    lines.append("}")
    lines.append("")
    return lines


def generate_decoder(function: dict) -> list[str]:
    name = function["name"]
    returns = function["returns"]
    lines = [
        f"/// Decodes the `{name}` call result into its typed form.",
        f"pub fn decode_{name}_result(value: &ScVal) -> Result<{value_type(returns)}, DecodeError> {{",
        "    crate::reject_contract_error(value)?;",
    ]
    lines.append(f"    {decode_expr(returns, 'value', name)}")
    lines.append("}")
    lines.append("")
    return lines


def generate_client(functions: list[dict]) -> list[str]:
    lines = [
        "/// A read-only client over any [`crate::ReadTransport`].",
        "pub struct ReadClient<T> {",
        "    transport: T,",
        "}",
        "",
        "impl<T> ReadClient<T> {",
        "    pub fn new(transport: T) -> Self {",
        "        Self { transport }",
        "    }",
        "",
        "    pub fn transport(&self) -> &T {",
        "        &self.transport",
        "    }",
        "}",
        "",
        "impl<T: crate::ReadTransport> ReadClient<T> {",
    ]
    for function in functions:
        name = function["name"]
        params = [
            f"{arg['name']}: {arg_type(arg['type'])}" for arg in function["args"]
        ]
        signature = ", ".join(["&self"] + params)
        lines += rustdoc(function.get("doc", ""), "    ")
        lines.append(
            f"    pub fn {name}({signature}) -> Result<{value_type(function['returns'])}, "
            "crate::CallError<T::Error>> {"
        )
        arguments = ", ".join(arg["name"] for arg in function["args"])
        lines.append(f"        let args = {name}_args({arguments})?;")
        lines.append(
            f"        let value = self.transport.simulate({name.upper()}, args)"
            ".map_err(crate::CallError::Transport)?;"
        )
        lines.append(f"        Ok(decode_{name}_result(&value)?)")
        lines.append("    }")
        lines.append("")
    lines.append("}")
    lines.append("")
    return lines


def generate_generated_rs() -> str:
    structs, enums, unions = reachable_types()
    functions = read_functions()
    arg_types: list[object] = [arg["type"] for function in functions for arg in function["args"]]
    imported = ["ScVal"]
    if _mentions(arg_types, "i128"):
        imported.append("Int128Parts")
    if _mentions(arg_types, "u128"):
        imported.append("UInt128Parts")
    xdr_import = (
        f"use stellar_xdr::{imported[0]};"
        if len(imported) == 1
        else f"use stellar_xdr::{{{', '.join(imported)}}};"
    )
    lines: list[str] = [HEADER.format(fingerprint=FINGERPRINT).rstrip("\n"), ""]
    lines += [
        "//! Generated read-only StreamPay bindings.",
        "//!",
        "//! Writes are out of scope: only operations the spec marks non-mutating are",
        "//! emitted, so this crate can never build or sign a state-changing call.",
        "",
        xdr_import,
        "",
        "use crate::{DecodeError, EncodeError};",
        "",
        f"pub const SPEC_FINGERPRINT: &str = {quote(FINGERPRINT)};",
        f"pub const CONTRACT_VERSION: &str = {quote(SPEC['contract']['version'])};",
        "",
    ]

    for name, constant in SPEC["constants"].items():
        rust_type = VALUE_TYPES.get(constant["type"], "u64")
        lines.append(f"pub const {name}: {rust_type} = {constant['value']};")
    lines.append("")

    lines.append("/// Contract method names, e.g. `GET_STREAM`.")
    for function in functions:
        lines.append(
            f"pub const {function['name'].upper()}: &str = {quote(function['name'])};"
        )
    lines.append("")

    for enum in enums:
        lines += generate_enum(enum)
    for union in unions:
        lines += generate_union(union)
    for struct in structs:
        lines += generate_struct(struct)

    lines += generate_error_enum()

    for function in functions:
        lines += generate_args(function)
    for function in functions:
        lines += generate_decoder(function)

    lines += generate_client(functions)
    return "\n".join(lines).rstrip("\n") + "\n"


def outputs(spec: dict, fingerprint: str, errors: list[tuple[int, str]]) -> dict[Path, str]:
    global SPEC, FINGERPRINT, ERRORS
    SPEC, FINGERPRINT, ERRORS = spec, fingerprint, errors
    return {RUST_SRC / "generated.rs": generate_generated_rs()}
