#!/usr/bin/env node
/**
 * Generates the UniFFI interface and error catalog for the mobile SDK.
 *
 * Inputs
 *   sdks/spec/streampay.spec.json   contract IR (read-only operations + Stream)
 *   frontend/lib/errors.ts          canonical error catalog (99 contract codes)
 *
 * Outputs
 *   sdks/mobile/src/streampay.udl
 *   sdks/mobile/src/error_catalog.rs
 *   sdks/mobile/bindings/INTERFACE
 *
 * The output is deterministic, so `--check` is the binding-freshness CI gate:
 * changing the spec or an error code without regenerating is a red build.
 * UniFFI itself then generates Kotlin/Swift from the UDL in CI, and those
 * generated bindings are compiled in the same job (compile smoke tests).
 *
 *   node sdks/mobile/scripts/generate-bindings.mjs
 *   node sdks/mobile/scripts/generate-bindings.mjs --check
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..");
const MOBILE = join(ROOT, "sdks", "mobile");
const SPEC_PATH = join(ROOT, "sdks", "spec", "streampay.spec.json");
const CATALOG_PATH = join(ROOT, "frontend", "lib", "errors.ts");
const FINGERPRINT_PATH = join(ROOT, "sdks", "spec", "FINGERPRINT");

const spec = JSON.parse(readFileSync(SPEC_PATH, "utf8"));
const fingerprint = readFileSync(FINGERPRINT_PATH, "utf8").trim();
const catalogText = readFileSync(CATALOG_PATH, "utf8");
const errors = [];
const errorPattern = /^\s*(\d+):\s*\{\s*code:\s*\d+,\s*name:\s*"(\w+)"/gm;
for (const match of catalogText.matchAll(errorPattern)) {
  errors.push([Number(match[1]), match[2]]);
}
errors.sort((left, right) => left[0] - right[0]);
if (errors.length !== 99) {
  throw new Error(`expected 99 error codes, read ${errors.length}`);
}
const reserved = new Set(["Transport", "Decode", "Unknown"]);
for (const [, name] of errors) {
  if (reserved.has(name)) throw new Error(`mobile-only error collides with ${name}`);
}

const HEADER = `// @generated by sdks/mobile/scripts/generate-bindings.mjs from sdks/spec/streampay.spec.json (sha256:${fingerprint}).
// Do not edit by hand: change the spec or the error catalog, then regenerate.
`;

function udl() {
  const stream = spec.structs.find((entry) => entry.name === "Stream");
  if (!stream) throw new Error("spec has no Stream struct");
  const status = spec.enums.find((entry) => entry.name === "StreamStatus");
  if (!status || status.encoding !== "symbol") {
    throw new Error("spec has no symbol-encoded StreamStatus");
  }
  const type = (value) => {
    if (typeof value === "string") {
      if (value === "u64" || value === "u32" || value === "bool") return value;
      if (value === "string" || value === "address") return "string";
      if (value === "i128" || value === "u128") return "string";
      return value;
    }
    if (value && "option" in value) return `${type(value.option)}?`;
    throw new Error(`unsupported Stream field type ${JSON.stringify(value)}`);
  };
  const fields = stream.fields.map((field) => {
    // i128 is encoded as a decimal string: UniFFI has no 128-bit scalar, and
    // truncating a token amount would corrupt balances.
    if (field.name === "deposit" || field.name === "withdrawn") {
      return `  string ${field.name};`;
    }
    return `  ${type(field.type)} ${field.name};`;
  });
  const variants = status.cases.map((entry) => `  "${entry.name}",`);
  const errorVariants = [...errors.map(([, name]) => name), ...[...reserved]];
  return `${HEADER}
namespace streampay {
  string spec_fingerprint();
};

enum StreamStatus {
${variants.join("\n")}
};

dictionary StreamView {
${fields.join("\n")}
};

[Error]
enum StreamPayError {
${errorVariants.map((name) => `  "${name}",`).join("\n")}
};

callback interface RpcReadTransport {
  [Throws=StreamPayError]
  string simulate(string contract_id, string function_name, string args_json);
};

interface StreamPayMobile {
  constructor(string contract_id, RpcReadTransport transport);

  [Throws=StreamPayError]
  StreamView get_stream(u64 stream_id);

  [Throws=StreamPayError]
  string available(u64 stream_id);

  [Throws=StreamPayError]
  sequence<u64> recipient_streams(string recipient, u32 offset, u32 limit);

  [Throws=StreamPayError]
  sequence<u64> sender_streams(string sender, u32 offset, u32 limit);

  [Throws=StreamPayError]
  StreamView decode_get_stream(string result_xdr);
};
`;
}

function rustCatalog() {
  const names = errors.map(([, name]) => name);
  const variants = [
    ...names.map((name) => `    ${name},`),
    "    Transport,",
    "    Decode,",
    "    Unknown,",
  ];
  const codes = errors.map(
    ([code, name]) => `            ${code} => Some(Self::${name}),`
  );
  const namesMatch = errors.map(([, name]) => `            Self::${name} => "${name}",`);
  const fromCodes = errors.map(([code, name]) => `            ${code} => Self::${name},`);
  return `${HEADER}
//! Generated mobile error catalog: one UniFFI exception per contract code.

use std::fmt;

#[derive(Clone, Debug, PartialEq, Eq)]
pub enum StreamPayError {
${variants.join("\n")}
}

impl StreamPayError {
    /// The contract code, or None for client-side transport/decode failures.
    pub fn code(&self) -> Option<u16> {
        match self {
${codes.join("\n")}
            Self::Transport | Self::Decode | Self::Unknown => None,
        }
    }

    /// The stable catalog name, identical to frontend/lib/errors.ts.
    pub fn name(&self) -> &'static str {
        match self {
${namesMatch.join("\n")}
            Self::Transport => "Transport",
            Self::Decode => "Decode",
            Self::Unknown => "Unknown",
        }
    }

    pub fn from_code(code: u16) -> Self {
        match code {
${fromCodes.join("\n")}
            _ => Self::Unknown,
        }
    }
}

impl fmt::Display for StreamPayError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.code() {
            Some(code) => write!(formatter, "{} (#{code})", self.name()),
            None => formatter.write_str(self.name()),
        }
    }
}

impl std::error::Error for StreamPayError {}
`;
}

function manifest() {
  const catalog = errors.map(([code, name]) => `${code}:${name}`).join("\n") + "\n";
  const digest = createHash("sha256").update(catalog).digest("hex");
  return `# @generated by sdks/mobile/scripts/generate-bindings.mjs. Do not edit.
schema=streampay-mobile-bindings/v1
specFingerprint=${fingerprint}
contractVersion=${spec.contract.version}
errors=${errors.length}
errorCatalogSha256=${digest}
methods=get_stream,available,recipient_streams,sender_streams,decode_get_stream
transports=RpcReadTransport
`;
}

const targets = new Map([
  [join(MOBILE, "src", "streampay.udl"), udl()],
  [join(MOBILE, "src", "error_catalog.rs"), rustCatalog()],
  [join(MOBILE, "bindings", "INTERFACE"), manifest()],
]);

const check = process.argv.includes("--check");
let stale = false;
for (const [path, content] of targets) {
  if (check) {
    const existing = existsSync(path) ? readFileSync(path, "utf8") : "";
    if (existing !== content) {
      stale = true;
      console.error(`${path} is stale`);
      console.error(existing.split("\n").slice(0, 8).join("\n"));
      console.error("--- expected ---");
      console.error(content.split("\n").slice(0, 8).join("\n"));
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content, "utf8");
    console.log(`wrote ${path}`);
  }
}
if (check) {
  if (stale) {
    console.error("mobile bindings are stale; run node sdks/mobile/scripts/generate-bindings.mjs");
    process.exit(1);
  }
  console.log(`mobile bindings match the spec: ${errors.length} error codes, sha256 ${fingerprint.slice(0, 12)}…`);
}
